import { test, expect, capture, checkLayout } from './fixtures';
import { serviceURL } from './environment';

test('Sidney saves all five steps, then a first meal reaches the shopping list', async ({ page, account }, info) => {
  await page.goto('/requirements');
  await page.getByRole('button', { name: 'Start guided setup', exact: true }).click();
  await expect(page.locator('html')).toHaveAttribute('data-theme', info.project.use.colorScheme === 'dark' ? 'dark' : 'light');
  await expect(page.getByRole('heading', { level: 1 })).toHaveText("Hello! I'm Sidney.");
  await page.getByLabel('Your preferred name').fill('Browser reviewer');
  await capture(page, info, 'sidney-name');
  await page.getByRole('button', { name: "Let's go!" }).click();
  await page.getByLabel('No kidney condition / other health goals', { exact: true }).check();
  await capture(page, info, 'sidney-stage');
  await page.getByRole('button', { name: 'Continue', exact: true }).click();
  await page.getByRole('checkbox', { name: 'Protein', exact: true }).check();
  await page.getByRole('checkbox', { name: 'Energy / calories', exact: true }).check();
  await page.getByLabel('About Protein', { exact: true }).click();
  await capture(page, info, 'sidney-selected-nutrients');
  await page.getByRole('button', { name: 'Continue', exact: true }).click();
  await page.getByLabel('Protein minimum (g/day)', { exact: true }).fill('80');
  await page.getByLabel('Protein maximum (g/day)', { exact: true }).fill('60');
  await page.getByRole('button', { name: 'Continue', exact: true }).click();
  await expect(page.locator('form [role=alert]')).toBeVisible();
  await capture(page, info, 'sidney-invalid-range');
  await page.getByLabel('Protein minimum (g/day)', { exact: true }).fill('40');
  await page.getByLabel('Energy minimum (kcal/day)', { exact: true }).fill('1800');
  await page.getByLabel('Energy maximum (kcal/day)', { exact: true }).fill('2200');
  await page.getByRole('button', { name: 'Continue', exact: true }).click();
  await page.getByLabel('No known food allergies', { exact: true }).check();
  await capture(page, info, 'sidney-allergies-and-summary');
  await page.getByRole('button', { name: 'Finish setup', exact: true }).click();
  await expect(page.getByRole('heading', { name: "You're all set!" })).toBeVisible();
  const diet = await page.request.get(`${serviceURL}/rest/v1/user_requirements`, { headers: account.headers });
  expect((await diet.json())[0]).toMatchObject({ preferred_name: 'Browser reviewer', onboarding_status: 'completed', food_allergies: [] });
  await expect(page.getByRole('link', { name: 'Plan My Week' })).toHaveAttribute('href', '/planner');
  await page.getByRole('button', { name: 'Back to My Diet', exact: true }).click();
  const proteinMinimum = page.getByLabel('Protein minimum (g/day)', { exact: true });
  await expect(proteinMinimum).toHaveValue('40');
  await expect(page.getByLabel('Protein maximum (g/day)', { exact: true })).toHaveValue('60');
  expect((await proteinMinimum.boundingBox())!.width, 'Saved protein values need readable input width').toBeGreaterThanOrEqual(80);
  await capture(page, info, 'my-diet-after-setup');
  await page.goto('/planner');
  const addBreakfast = page.getByRole('button', { name: /Add breakfast/i }).filter({ visible: true }).first();
  await addBreakfast.click();
  await page.getByRole('button', { name: /Scrambled Egg & Tomato Toast/ }).click();
  await expect(page.getByRole('link', { name: 'View Scrambled Egg & Tomato Toast recipe' }).filter({ visible: true }).first()).toBeVisible();
  await capture(page, info, 'first-meal-planned');
  await page.getByRole('button', { name: '1 person', exact: true }).filter({ visible: true }).first().click();
  await page.getByRole('button', { name: 'Increase people', exact: true }).click();
  await capture(page, info, 'meal-people-adjustment');
  await page.getByRole('button', { name: 'Done', exact: true }).click();
  await expect.poll(async () => {
    const response = await page.request.get(`${serviceURL}/rest/v1/user_meal_plans`, { headers: account.headers });
    return (await response.json())[0]?.meal_people?.Monday?.Breakfast;
  }).toBe(2);
  await page.reload();
  await expect(page.getByRole('link', { name: 'View Scrambled Egg & Tomato Toast recipe' }).filter({ visible: true }).first()).toBeVisible();
  await page.goto('/shopping');
  await expect(page.locator('.shopping-list-item').first()).toBeVisible();
  await expect(page.locator('.shopping-list-item').filter({ has: page.getByRole('checkbox', { name: /^Eggs?$/ }) }).locator('.shopping-list-item-quantity')).toHaveText('2');
  await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem('shopping-data') ?? '{}').plannerCounts?.['scrambled-egg-tomato-toast'])).toBe(2);
  const checkbox = page.locator('.shopping-list-item input[type=checkbox]').first();
  await checkbox.check();
  const name = await checkbox.locator('..').innerText();
  await capture(page, info, 'shopping-checklist');
  await page.reload();
  await expect(page.getByRole('checkbox', { name: name.trim(), exact: true })).toBeChecked();
  await checkLayout(page);
});

test('failed saving retains answers, retry succeeds, and reopening resumes the saved step', async ({ page }, info) => {
  await page.goto('/requirements');
  await page.getByRole('button', { name: 'Start guided setup', exact: true }).click();
  await page.getByLabel('Your preferred name').fill('Retained answer');
  await page.route('**/rest/v1/user_requirements*', async route => {
    if (route.request().method() === 'POST') {
      await route.fulfill({ status: 503, contentType: 'application/json', body: '{"message":"Simulated unavailable service"}' });
    } else await route.continue();
  });
  await page.getByRole('button', { name: "Let's go!" }).click();
  await expect(page.locator('form [role=alert]')).toBeVisible();
  await expect(page.getByLabel('Your preferred name')).toHaveValue('Retained answer');
  await expect(page.getByRole('heading', { name: "You're all set!" })).toHaveCount(0);
  await capture(page, info, 'save-error-with-answers');
  await page.unroute('**/rest/v1/user_requirements*');
  await page.getByRole('button', { name: "Let's go!" }).click();
  await expect(page.getByRole('heading', { name: 'Which best describes you?' })).toBeVisible();
  await page.reload();
  await page.getByRole('button', { name: 'Start guided setup', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Which best describes you?' })).toBeVisible();
  await page.getByRole('button', { name: 'Back', exact: true }).click();
  await expect(page.getByLabel('Your preferred name')).toHaveValue('Retained answer');
  await page.getByRole('button', { name: 'Skip for now', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Start guided setup', exact: true })).toBeVisible();
  await capture(page, info, 'my-diet-after-leaving');
});
